def main():
    rows = [{'subject': subject, 'body': body} for examples in EXAMPLES.values() for subject, body in examples]
    labels = [category for category, examples in EXAMPLES.items() for _ in examples]
    classifier = model().fit([features(row) for row in rows], labels)
    output = ROOT / 'seed'
    output.mkdir(exist_ok=True)
    joblib.dump(classifier, output / 'public-classifier.joblib')
    report = {
        'publicSeed': True,
        'examples': len(rows),
        'enabled': True,
        'threshold': THRESHOLD,
        'categoryCounts': dict(Counter(labels)),
    }
    (output / 'public-report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f'Built public classifier from {len(rows)} fabricated examples.')


if __name__ == '__main__':
    main()
